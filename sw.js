// `plume-` est l'ancien nom du site : ses caches sont encore supprimés.
const PREFIXES_CACHE = ['lexia-', 'plume-'];
const PAGE_D_ACCUEIL = 'index.html';
const MESSAGE_ACTIVATION = 'ACTIVER_NOUVELLE_VERSION';

/** Met tout le site en cache. Le nouveau worker reste « en attente » tant que l'élève n'a pas accepté. */
async function precacher() {
  const cache = await caches.open(VERSION_CACHE);
  await cache.addAll(FICHIERS_A_PRECACHER);
}

/** Supprime les caches des versions précédentes. */
async function supprimerAnciensCaches() {
  const noms = await caches.keys();
  const anciens = noms.filter(
    (nom) => PREFIXES_CACHE.some((prefixe) => nom.startsWith(prefixe)) && nom !== VERSION_CACHE,
  );
  await Promise.all(anciens.map((nom) => caches.delete(nom)));
}

/** Le cache d'abord ; une page inconnue hors ligne retombe sur l'accueil. */
async function repondre(requete) {
  const enCache = await caches.match(requete);
  if (enCache) {
    return enCache;
  }
  try {
    return await fetch(requete);
  } catch (erreur) {
    if (requete.mode === 'navigate') {
      return caches.match(PAGE_D_ACCUEIL);
    }
    throw erreur;
  }
}

self.addEventListener('install', (evenement) => {
  evenement.waitUntil(precacher());
});

self.addEventListener('activate', (evenement) => {
  evenement.waitUntil(supprimerAnciensCaches().then(() => self.clients.claim()));
});

self.addEventListener('fetch', (evenement) => {
  const { request } = evenement;
  const estDuSite = new URL(request.url).origin === self.location.origin;
  if (request.method !== 'GET' || !estDuSite) {
    return;
  }
  evenement.respondWith(repondre(request));
});

self.addEventListener('message', (evenement) => {
  if (evenement.data && evenement.data.type === MESSAGE_ACTIVATION) {
    self.skipWaiting();
  }
});
